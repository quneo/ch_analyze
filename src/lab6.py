import numpy as np


# Узлы, в которых известны значения функции, и точка дифференцирования.
xi = np.array([138, 139, 141, 143, 145, 147], dtype=float)
x0 = 142
M = 4

# h_i - смещения узлов относительно точки x0.
h = xi - x0

# Условия точности для формулы первой производной:
# sum c_i * h_i^0 = 0, sum c_i * h_i^1 = 1,
# sum c_i * h_i^k = 0 для k = 2..M.
A = np.array([
    h**k for k in range(M + 1)
], dtype=float)

b = np.zeros(M + 1)
b[1] = 1

# Берем минимальную по норме формулу, так как узлов больше, чем условий.
c = A.T @ np.linalg.solve(A @ A.T, b)

print("Коэффициенты разностной формулы:")
print(c)

print("Проверка условий точности:")
print(A @ c)
