import numpy as np


# Задача: найти решение переопределенной системы A x ~= b
# при точном выполнении линейных ограничений C x = d.
A = np.array([
    [0.81472, 0.63236, 0.95751, 0.95717, 0.42176],
    [0.90579, 0.09754, 0.96489, 0.48538, 0.91574],
    [0.12699, 0.27850, 0.15761, 0.80028, 0.79221],
    [0.91338, 0.54688, 0.97059, 0.14189, 0.95949]
], dtype=float)

C = np.array([
    [0.67874, 0.39223, 0.70605, 0.046171, 0.69483],
    [0.75774, 0.65548, 0.031833, 0.097132, 0.31710],
    [0.74313, 0.17119, 0.27692, 0.82346, 0.95022]
], dtype=float)

b = np.array([0.65574, 0.035712, 0.84913, 0.93399], dtype=float)
d = np.array([0.034446, 0.43874, 0.38156], dtype=float)

m, n = A.shape
p = C.shape[0]

# Система ККТ для метода множителей Лагранжа:
# 2 A^T A x + C^T lambda = 2 A^T b
# C x = d
K = np.block([
    [2 * A.T @ A, C.T],
    [C, np.zeros((p, p))]
])

rhs = np.concatenate([2 * A.T @ b, d])
sol = np.linalg.solve(K, rhs)

# Первые n компонент - искомый x, оставшиеся - множители Лагранжа.
x = sol[:n]
lam = sol[n:]

print("x =", x)
print("C x =", C @ x)
print("d   =", d)
print("||b - A x|| =", np.linalg.norm(b - A @ x))
